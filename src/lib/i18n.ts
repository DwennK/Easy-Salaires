export function tr(key: string, l: Lang = lang.value): string {
  if (key.startsWith("missing:")) {
    const [, rubric, side] = key.split(":");
    return `${tr(rubric!, l)} — ${tr(side === "employee" ? "employeeShare" : "employerShare", l)} : ${tr("required", l)}`;
  }
  return pairs[key]?.[l === "fr" ? 0 : 1] ?? key;
}
